impl OmcpNode {
    fn queue_app(
        &self,
        contact_id: &str,
        content: AppContent,
        burn: Option<BurnSpec>,
        mime: Option<String>,
    ) -> Result<String, FfiError> {
        let id = parse_id(contact_id)?;
        let header = burn.map(|b| b.header()).transpose()?;
        let inner = core_burn::encode_app(header.as_ref(), &content)?;
        let envelope_id = random_id16()?;
        let now = now_ms();
        let mut st = self.inner.lock();
        if !st.contacts.contains_key(&id) {
            return Err(FfiError::UnknownContact);
        }
        let mut staged_burn = BurnStore::default();
        if let Some(h) = header {
            let body: &[u8] = match &content {
                AppContent::Text(t) => t.as_bytes(),
                AppContent::Media { bytes, .. } => bytes,
                _ => &[],
            };
            staged_burn.insert(envelope_id, h, body, now)?;
        }
        let snapshot = staged_burn.snapshot(&envelope_id);
        let text = match (&content, header) {
            (AppContent::Text(t), None) => t.clone(),
            _ => String::new(),
        };
        let message = MessageRec {
            id: envelope_id,
            peer: id,
            mine: true,
            time_ms: now,
            status: st::STATUS_QUEUED,
            text,
            mime: mime.clone(),
            burn: header.map(|h| h.encode().to_vec()),
            burn_state: if header.is_some() {
                st::BURN_UNOPENED
            } else {
                st::BURN_NONE
            },
            burn_at_ms: None,
            file: None,
        };
        let q = Queued {
            envelope_id,
            created_ms: now,
            inner: Zeroizing::new(inner),
            control: false,
        };
        st.db().transaction_with::<_, FfiError>(|db| {
            if let Some(snapshot) = &snapshot {
                db.put_burn(snapshot, &id, st::BurnDir::Out, mime.as_deref())?;
            }
            db.put_message(&message)?;
            db.put_outbox(
                &st::OutboxRec {
                    id: envelope_id,
                    peer: id,
                    created_ms: now,
                    inner: q.inner.to_vec(),
                    control: false,
                    burn: false,
                },
                snapshot.as_ref().map(|s| &*s.key),
            )?;
            Ok(())
        })?;
        if let Some(snapshot) = snapshot {
            st.burn_out.restore(snapshot);
            st.burn_meta
                .insert(envelope_id, BurnMeta { peer: id, mime });
        }
        st.queues.entry(id).or_default().push_back(q);
        Ok(hex::encode(envelope_id))
    }

    fn info(&self, id: &[u8; 32], c: &Contact) -> ContactInfo {
        contact_info(&self.inner, id, c)
    }

    fn new_link(&self, role: Role, peer: Option<[u8; 32]>) -> Result<Arc<MeshLink>, FfiError> {
        let mut st = self.inner.lock();
        if st.active_links.len() >= MAX_ACTIVE_LINKS {
            return Err(FfiError::State {
                msg: "active link resource budget exhausted; close an idle link".into(),
            });
        }
        let handle = st.next_link;
        st.next_link = st
            .next_link
            .checked_add(1)
            .ok_or_else(|| invalid("link handle exhausted"))?;
        st.active_links.insert(handle);
        Ok(Arc::new(MeshLink {
            node: self.inner.clone(),
            handle,
            state: Mutex::new(LinkState {
                role,
                peer,
                hs_buf: Vec::new(),
                hs_total: 0,
                hs_next: 0,
                pending: None,
                last_committed: None,
            }),
        }))
    }
}

