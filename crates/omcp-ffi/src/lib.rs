fn chunk_handshake(msg: &[u8], out: &mut Vec<Vec<u8>>) -> Result<(), FfiError> {
    if msg.is_empty() || msg.len() > MAX_HANDSHAKE_BYTES {
        return Err(invalid("handshake size outside chunk budget"));
    }
    let total = msg.len().div_ceil(HANDSHAKE_CHUNK) as u8;
    for (i, c) in msg.chunks(HANDSHAKE_CHUNK).enumerate() {
        let mut p = Vec::with_capacity(3 + c.len());
        p.extend_from_slice(&[PDU_HANDSHAKE, i as u8, total]);
        p.extend_from_slice(c);
        out.push(p);
    }
    Ok(())
}

#[uniffi::export]
impl MeshLink {
    /// Initiator: emit handshake message 1. Responder: no-op.
    pub fn start(&self) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        let result = (|| {
            if st.pending.is_none() {
                if let Role::Initiator(init) = &mut st.role {
                    let m1 = init.write_message_1_with(|h| self.node.handshake_payload(h))?;
                    chunk_handshake(&m1, &mut out.outgoing)?;
                }
                Self::finish_batch(&mut st, &mut out)?;
            }
            Self::fill(&st, &mut out);
            Ok(out)
        })();
        if result.is_err() {
            self.shutdown_locked(&mut st);
        }
        result
    }

    /// Feed one PDU received from the peer (Inbox write or Outbox notify).
    pub fn on_pdu(&self, pdu: Vec<u8>) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let result = self.on_pdu_locked(&mut st, &pdu);
        if result.is_err() {
            // A nonce may have advanced. Retire keys and replay durable logical
            // work only after a new handshake, never on this failed session.
            self.shutdown_locked(&mut st);
        }
        result
    }

    /// Persist text before generating PDUs, even on an established link.
    pub fn send_text(&self, text: String) -> Result<LinkOutput, FfiError> {
        let peer = self.lock().peer.ok_or(FfiError::UnknownContact)?;
        OmcpNode {
            inner: self.node.clone(),
        }
        .queue_text(hex::encode(peer), text)?;
        self.flush()
    }

    /// Prepare a bounded batch. While one is outstanding this emits no PDUs.
    pub fn flush(&self) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        let result = self.flush_locked(&mut st, &mut out).and_then(|()| {
            Self::finish_batch(&mut st, &mut out)?;
            Self::fill(&st, &mut out);
            Ok(out)
        });
        if result.is_err() {
            self.shutdown_locked(&mut st);
        }
        result
    }

    /// Atomically retire logical work after EVERY PDU in the batch was accepted
    /// by the OS transport. Does not imply peer receipt. A duplicate of the most
    /// recent successful commit is a no-op; stale/wrong tokens cannot mutate.
    pub fn commit_outgoing(&self, token: String) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        if !matches!(st.role, Role::Closed) && st.last_committed.as_ref() == Some(&token) {
            let mut out = LinkOutput::default();
            Self::fill(&st, &mut out);
            out.more_pending = self.has_work(&st);
            return Ok(out);
        }
        if st.pending.as_ref().is_none_or(|p| p.token != token) {
            return Err(invalid("stale or unknown outgoing batch token"));
        }
        let result = self.commit_locked(&mut st);
        if result.is_err() {
            self.shutdown_locked(&mut st);
        }
        result
    }

    /// Retire a failed/abandoned transport batch and its key session. Logical
    /// durable work remains queued for a fresh link. Never skip/retry a PDU.
    pub fn abort_outgoing(&self, token: String) -> Result<(), FfiError> {
        let mut st = self.lock();
        if st.pending.as_ref().is_none_or(|p| p.token != token) {
            return Err(invalid("stale or unknown outgoing batch token"));
        }
        self.shutdown_locked(&mut st);
        Ok(())
    }

    pub fn is_established(&self) -> bool {
        matches!(self.lock().role, Role::Up(_))
    }

    /// Tear down; the peer no longer counts as nearby.
    pub fn shutdown(&self) {
        self.shutdown_locked(&mut self.lock());
    }
}

impl MeshLink {
    fn shutdown_locked(&self, st: &mut LinkState) {
        st.role = Role::Closed;
        st.pending = None;
        st.last_committed = None;
        st.hs_buf = Vec::new();
        st.hs_total = 0;
        st.hs_next = 0;
        let mut node = self.node.lock();
        node.links_up.remove(&self.handle);
        node.active_links.remove(&self.handle);
        node.outgoing_owner.retain(|_, owner| *owner != self.handle);
        if let Some(peer) = st.peer {
            if !node.links_up.values().any(|p| *p == peer) {
                let _ = node.pause_transfers(&peer);
            }
        }
    }

    fn on_pdu_locked(&self, st: &mut LinkState, pdu: &[u8]) -> Result<LinkOutput, FfiError> {
        let mut out = LinkOutput::default();
        let (&kind, body) = pdu.split_first().ok_or_else(|| invalid("empty pdu"))?;
        match kind {
            PDU_HANDSHAKE => {
                if !matches!(st.role, Role::Initiator(_) | Role::Responder(_)) {
                    return Err(FfiError::State {
                        msg: "unexpected handshake message".into(),
                    });
                }
                if body.len() < 2 || body.len() > 2 + HANDSHAKE_CHUNK {
                    return Err(invalid("handshake chunk exceeds PDU budget"));
                }
                let (idx, total) = (body[0], body[1]);
                if total == 0 || idx >= total || u16::from(idx) != st.hs_next {
                    return Err(invalid("handshake chunk index/count/order"));
                }
                if st.hs_next == 0 {
                    st.hs_total = total;
                    // Exact reservation avoids geometric growth beyond the budget.
                    st.hs_buf
                        .try_reserve_exact(total as usize * HANDSHAKE_CHUNK)
                        .map_err(|_| invalid("handshake allocation failed"))?;
                } else if total != st.hs_total {
                    return Err(invalid("handshake chunk count mismatch"));
                }
                if body.len() - 2 > MAX_HANDSHAKE_BYTES - st.hs_buf.len() {
                    return Err(invalid("handshake byte budget exhausted"));
                }
                st.hs_buf.extend_from_slice(&body[2..]);
                st.hs_next += 1;
                if st.hs_next == u16::from(total) {
                    let msg = std::mem::take(&mut st.hs_buf);
                    st.hs_next = 0;
                    st.hs_total = 0;
                    self.complete_handshake(st, &msg, &mut out)?;
                }
            }
            PDU_LINK => {
                let peer = st.peer;
                let Role::Up(up) = &mut st.role else {
                    return Err(FfiError::State {
                        msg: "link fragment before handshake".into(),
                    });
                };
                let peer = peer.ok_or(FfiError::UnknownContact)?;
                if let Some(bytes) = up.reasm.push_frame(&mut up.link, body, Instant::now())? {
                    let env = EnvelopeV1::decode(&bytes)?;
                    let key = up.recv_key();
                    let (ct, plain) = open_app_envelope(&key, &peer, &env, &mut up.app_recv)?;
                    let plain = Zeroizing::new(plain);
                    let mut node = self.node.lock();
                    // User-message replay is durable and peer-bound, not the
                    // short-lived gossip cache (which must not hide DB retries).
                    let user_message = ct == CONTENT_TYPE_TEXT_PLAIN
                        || matches!(
                            core_burn::decode_app(&plain)?,
                            (_, AppContent::Text(_) | AppContent::Media { .. })
                        );
                    let mut seen_key = blake3::Hasher::new();
                    seen_key.update(&peer);
                    seen_key.update(&env.envelope_id);
                    let seen_key: [u8; 16] = seen_key.finalize().as_bytes()[..16]
                        .try_into()
                        .expect("hash prefix");
                    if user_message || !node.seen.contains(&seen_key, Instant::now()) {
                        let from = (
                            out.file_progress.len(),
                            out.files.len(),
                            out.file_failures.len(),
                        );
                        Self::deliver(&mut node, peer, &env, ct, &plain, &mut out)?;
                        node.persist_file_events(&mut out, from, now_ms())?;
                        if !user_message {
                            node.seen.check_and_insert(seen_key, Instant::now());
                        }
                    }
                    let replies = node.queues.get(&peer).is_some_and(|q| !q.is_empty())
                        || node.files.out.get(&peer).is_some_and(|q| !q.is_empty());
                    drop(node);
                    if replies {
                        self.flush_locked(st, &mut out)?;
                    }
                }
            }
            _ => return Err(invalid("unknown pdu kind")),
        }
        Self::finish_batch(st, &mut out)?;
        Self::fill(st, &mut out);
        Ok(out)
    }

    fn lock(&self) -> MutexGuard<'_, LinkState> {
        self.state.lock().unwrap_or_else(|p| p.into_inner())
    }

    fn fill(st: &LinkState, out: &mut LinkOutput) {
        out.established = matches!(st.role, Role::Up(_));
        out.peer_contact_id = st.peer.map(hex::encode);
    }

    /// Route one decrypted message: text, burn content into the shredding store, or `OPENED`.
    fn deliver(
        node: &mut NodeState,
        peer: [u8; 32],
        env: &EnvelopeV1,
        ct: u8,
        plain: &[u8],
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let mut rt = ReceivedText {
            contact_id: hex::encode(peer),
            text: String::new(),
            created_ms: env.created_ms,
            envelope_id_hex: hex::encode(env.envelope_id),
            burn: None,
            mime: None,
        };
        let received = |text: &str, mime: Option<String>, burn: Option<&BurnHeader>| MessageRec {
            id: env.envelope_id,
            peer,
            mine: false,
            time_ms: env.created_ms,
            status: st::STATUS_RECEIVED,
            text: text.into(),
            mime,
            burn: burn.map(|h| h.encode().to_vec()),
            burn_state: if burn.is_some() {
                st::BURN_UNOPENED
            } else {
                st::BURN_NONE
            },
            burn_at_ms: None,
            file: None,
        };
        if ct == CONTENT_TYPE_TEXT_PLAIN {
            rt.text = String::from_utf8(plain.to_vec()).map_err(|_| invalid("utf8"))?;
            if Self::received_user_before(node, &peer, &env.envelope_id)? {
                return Ok(());
            }
            Self::persist_received_user(node, &received(&rt.text, None, None), None)?;
            out.received.push(rt);
            return Ok(());
        }
        let (burn, content) = core_burn::decode_app(plain)?;
        if matches!(&content, AppContent::Text(_) | AppContent::Media { .. })
            && Self::received_user_before(node, &peer, &env.envelope_id)?
        {
            return Ok(());
        }
        match (burn, content) {
            (_, AppContent::Opened(r)) => {
                // OPENED is valid only for our outgoing burn message, never a
                // received message whose peer happens to match burn_meta.
                let Some(message) = node.db().message(&r.msg_id)? else {
                    return Ok(());
                };
                if !message.mine || message.peer != peer || message.burn.is_none() {
                    return Ok(());
                }
                let Some(meta) = node.burn_meta.get(&r.msg_id) else {
                    return Ok(());
                };
                if meta.peer != peer {
                    return Ok(()); // only the recipient may open it
                }
                let media = meta.mime.is_some();
                let shredded = node
                    .burn_out
                    .on_remote_opened(&r.msg_id, r.opened_ms, media)
                    || !node.burn_out.is_live(&r.msg_id);
                if shredded {
                    node.discard_queued(&r.msg_id);
                }
                let burn_at_ms = node.burn_out.burn_at(&r.msg_id);
                node.persist_burn(&r.msg_id)?;
                if shredded {
                    node.burn_message_now(&r.msg_id)?;
                } else {
                    node.update_message(&r.msg_id, |m| {
                        m.burn_state = st::BURN_OPEN;
                        m.burn_at_ms = burn_at_ms;
                    })?;
                }
                out.opened.push(OpenedEvent {
                    contact_id: hex::encode(peer),
                    msg_id_hex: hex::encode(r.msg_id),
                    opened_ms: r.opened_ms,
                    shredded,
                    burn_at_ms,
                });
            }
            (None, AppContent::FileMeta(b)) => {
                // Transfer IDs share the durable message namespace. Check its
                // owner before allocating a receiver or emitting a file result.
                if let Some(id) = b.get(..16) {
                    let id: [u8; 16] = id.try_into().expect("16-byte transfer id");
                    if node.db().message(&id)?.is_none() && node.db().received_before(&peer, &id)? {
                        return Ok(());
                    }
                    if let Some(m) = node.db().message(&id)? {
                        // A completed transfer ID is immutable. Replayed offers
                        // and chunks must not discard its saved path or emit a
                        // second file. Explicit missing-media states still admit
                        // the existing hash-verified re-fetch flow.
                        if m.peer == peer
                            && m.file.as_ref().is_some_and(|f| {
                                matches!(f.state, st::FILE_RECEIVED | st::FILE_FINALIZING)
                            })
                        {
                            return Ok(());
                        }
                        if m.peer == peer {
                            if let (Some(f), Some(meta_bytes)) = (m.file.as_ref(), b.get(48..)) {
                                if let Ok(meta) = omcp_core::files::FileMeta::decode(meta_bytes) {
                                    if f.hash.as_deref().is_some_and(|h| h != meta.content_hash)
                                        || (f.hash.is_some() && f.size != meta.size)
                                    {
                                        out.file_failures.push(FileFailure {
                                            transfer_id_hex: hex::encode(id),
                                            contact_id: hex::encode(peer),
                                            reason: "integrity".into(),
                                        });
                                        return Ok(());
                                    }
                                }
                            }
                        }
                        if !persist::accepts_incoming_file(&m, &peer) {
                            out.file_failures.push(FileFailure {
                                transfer_id_hex: hex::encode(id),
                                contact_id: hex::encode(peer),
                                reason: "invalid".into(),
                            });
                            return Ok(());
                        }
                    }
                }
                node.refresh_receive_budget()?;
                files::on_offer(&mut node.files, peer, &b, out)
            }
            (None, AppContent::FileChunk(b)) => files::on_chunk(&mut node.files, peer, &b, out),
            (Some(_), AppContent::FileMeta(_) | AppContent::FileChunk(_)) => {
                return Err(invalid("burn file"))
            }
            (None, AppContent::MediaControl(c)) => node.on_media_control(peer, c, out)?,
            (Some(_), AppContent::MediaControl(_)) => return Err(invalid("burn control")),
            (None, AppContent::Text(t)) => {
                Self::persist_received_user(node, &received(&t, None, None), None)?;
                rt.text = t;
                out.received.push(rt);
            }
            (None, AppContent::Media { mime, .. }) => {
                // TODO(M5.x): non-burn media goes through the chunked file path.
                Self::persist_received_user(node, &received("", Some(mime.clone()), None), None)?;
                rt.mime = Some(mime);
                out.received.push(rt);
            }
            (Some(h), c) => {
                let (body, mime) = match &c {
                    AppContent::Text(t) => (t.as_bytes(), None),
                    AppContent::Media { mime, bytes } => (bytes.as_slice(), Some(mime.clone())),
                    AppContent::Opened(_)
                    | AppContent::FileMeta(_)
                    | AppContent::FileChunk(_)
                    | AppContent::MediaControl(_) => unreachable!(),
                };
                // Stage the burn entry separately; failed persistence must not
                // leave a live unrecorded copy or consume the replay ID.
                let mut staged = BurnStore::default();
                staged.insert(env.envelope_id, h, body, env.created_ms)?;
                let snapshot = staged.snapshot(&env.envelope_id).expect("staged burn");
                Self::persist_received_user(
                    node,
                    &received("", mime.clone(), Some(&h)),
                    Some(&snapshot),
                )?;
                node.burn_in.restore(snapshot);
                node.burn_meta.insert(
                    env.envelope_id,
                    BurnMeta {
                        peer,
                        mime: mime.clone(),
                    },
                );
                rt.burn = Some(BurnSpec::from_header(&h));
                rt.mime = mime;
                out.received.push(rt);
            }
        }
        Ok(())
    }

    fn received_user_before(
        node: &NodeState,
        peer: &[u8; 32],
        id: &[u8; 16],
    ) -> Result<bool, FfiError> {
        if let Some(m) = node.db().message(id)? {
            // Message IDs are a shared durable namespace: an authenticated peer
            // may not overwrite another peer, our own send, or a file record.
            if m.peer != *peer || m.mine || m.file.is_some() {
                return Err(invalid("received message ID ownership mismatch"));
            }
            return Ok(true);
        }
        Ok(node.db().received_before(peer, id)?)
    }

    fn persist_received_user(
        node: &NodeState,
        message: &MessageRec,
        burn: Option<&core_burn::BurnSnapshot>,
    ) -> Result<(), FfiError> {
        node.db().transaction_with(|db| {
            if let Some(snapshot) = burn {
                db.put_burn(
                    snapshot,
                    &message.peer,
                    st::BurnDir::In,
                    message.mime.as_deref(),
                )?;
            }
            db.put_message(message)?;
            db.record_received(&message.peer, &message.id)?;
            Ok(())
        })
    }

    fn seal_into(
        node: &NodeInner,
        up: &mut Established,
        q: &Queued,
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let env = seal_inner_envelope(
            &up.send_key(),
            &node.peer_id,
            q.envelope_id,
            &q.inner,
            q.created_ms,
            &mut up.app_send,
            TTL_HOPS,
        )?;
        let bytes = env.encode()?;
        for f in fragment_and_seal(
            &mut up.link,
            &bytes,
            random_frag_id()?,
            LINK_FRAGMENT_PAYLOAD,
        )? {
            let mut p = Vec::with_capacity(1 + f.len());
            p.push(PDU_LINK);
            p.extend_from_slice(&f);
            out.outgoing.push(p);
        }
        Ok(())
    }

    fn has_work(&self, st: &LinkState) -> bool {
        let Some(peer) = st.peer else { return false };
        let node = self.node.lock();
        !node
            .outgoing_owner
            .get(&peer)
            .is_some_and(|h| *h != self.handle)
            && (node.queues.get(&peer).is_some_and(|q| !q.is_empty())
                || node.files.out.get(&peer).is_some_and(|q| !q.is_empty()))
    }

    fn finish_batch(st: &mut LinkState, out: &mut LinkOutput) -> Result<(), FfiError> {
        if !out.outgoing.is_empty() {
            if st.pending.is_none() {
                st.pending = Some(PendingBatch {
                    token: hex::encode(random_id16()?),
                    queued: Vec::new(),
                    file: None,
                });
            }
            out.batch_token = st.pending.as_ref().map(|p| p.token.clone());
        }
        Ok(())
    }

    fn flush_locked(&self, st: &mut LinkState, out: &mut LinkOutput) -> Result<(), FfiError> {
        if st.pending.is_some() {
            out.more_pending = self.has_work(st);
            return Ok(());
        }
        let (Some(peer), Role::Up(up)) = (st.peer, &mut st.role) else {
            return Ok(());
        };
        let mut node = self.node.lock();
        if node
            .outgoing_owner
            .get(&peer)
            .is_some_and(|h| *h != self.handle)
        {
            return Ok(());
        }
        // Shredded burn payloads must not survive in the in-memory send queue.
        let expired: HashSet<_> = node
            .queues
            .get(&peer)
            .into_iter()
            .flatten()
            .filter(|q| {
                node.burn_meta.contains_key(&q.envelope_id)
                    && !node.burn_out.is_live(&q.envelope_id)
            })
            .map(|q| q.envelope_id)
            .collect();
        for id in &expired {
            node.db().delete_outbox(id)?;
        }
        if let Some(q) = node.queues.get_mut(&peer) {
            q.retain(|q| !expired.contains(&q.envelope_id));
        }
        let mut messages: Vec<Queued> = node
            .queues
            .get(&peer)
            .into_iter()
            .flatten()
            .take(TEXTS_PER_FLUSH)
            .cloned()
            .collect();
        let queued = messages
            .iter()
            .map(|q| (q.envelope_id, q.control))
            .collect();
        let file = if let Some(f) = node.files.out.get(&peer).and_then(|q| q.front()) {
            let mut cursor = if f.link == Some(self.handle) {
                f.cursor
            } else {
                0
            };
            if f.link != Some(self.handle) {
                messages.push(Queued {
                    envelope_id: random_id16()?,
                    created_ms: now_ms(),
                    inner: f.offer.clone(),
                    control: true,
                });
            }
            for c in f
                .chunks
                .iter()
                .skip(cursor)
                .take(files::FILE_CHUNKS_PER_FLUSH)
            {
                messages.push(Queued {
                    envelope_id: random_id16()?,
                    created_ms: now_ms(),
                    inner: c.clone(),
                    control: true,
                });
                cursor += 1;
            }
            let mut progress = f.progress(&peer);
            progress.done_chunks = cursor as u32;
            Some(PendingFile {
                id: f.id,
                cursor,
                progress,
            })
        } else {
            None
        };
        if messages.is_empty() {
            if node.outgoing_owner.get(&peer) == Some(&self.handle) {
                node.outgoing_owner.remove(&peer);
            }
            return Ok(());
        }
        node.outgoing_owner.insert(peer, self.handle);
        drop(node);
        st.pending = Some(PendingBatch {
            token: hex::encode(random_id16()?),
            queued,
            file,
        });
        for q in &messages {
            Self::seal_into(&self.node, up, q, out)?;
        }
        // This includes the prepared batch until commit. The commit result gives
        // the authoritative remainder, including replies queued while pending.
        out.more_pending = true;
        Ok(())
    }

    fn commit_locked(&self, st: &mut LinkState) -> Result<LinkOutput, FfiError> {
        let batch = st.pending.as_ref().expect("validated pending batch");
        let mut out = LinkOutput::default();
        let mut node = self.node.lock();
        if let Some(peer) = st.peer {
            let live: Vec<_> = batch
                .queued
                .iter()
                .copied()
                .filter(|(id, _)| {
                    node.queues
                        .get(&peer)
                        .is_some_and(|q| q.iter().any(|q| q.envelope_id == *id))
                })
                .collect();
            let file = batch.file.as_ref().filter(|p| {
                node.files
                    .out
                    .get(&peer)
                    .is_some_and(|q| q.iter().any(|f| f.id == p.id))
            });
            let file_commit = file.map(|p| st::OutgoingFileCommit {
                id: p.id,
                done_bytes: if p.progress.total_chunks == 0 {
                    p.progress.size
                } else {
                    p.progress.size * u64::from(p.progress.done_chunks)
                        / u64::from(p.progress.total_chunks)
                },
                complete: p.progress.done_chunks >= p.progress.total_chunks,
            });
            node.db().commit_outgoing(&peer, &live, file_commit)?;
            let ids: HashSet<_> = live.iter().map(|(id, _)| *id).collect();
            if let Some(q) = node.queues.get_mut(&peer) {
                q.retain(|q| !ids.contains(&q.envelope_id));
            }
            out.flushed = live
                .iter()
                .filter(|(id, control)| {
                    !*control && (!node.burn_meta.contains_key(id) || node.burn_out.is_live(id))
                })
                .count() as u32;
            if let Some(p) = file {
                if let Some(q) = node.files.out.get_mut(&peer) {
                    if let Some(f) = q.iter_mut().find(|f| f.id == p.id) {
                        f.cursor = p.cursor;
                        f.link = Some(self.handle);
                    }
                    q.retain(|f| f.id != p.id || p.cursor < f.chunks.len());
                }
                out.file_progress.push(p.progress.clone());
            }
            out.more_pending = node.queues.get(&peer).is_some_and(|q| !q.is_empty())
                || node.files.out.get(&peer).is_some_and(|q| !q.is_empty());
            if !out.more_pending && node.outgoing_owner.get(&peer) == Some(&self.handle) {
                node.outgoing_owner.remove(&peer);
            }
        }
        st.last_committed = Some(batch.token.clone());
        st.pending = None;
        Self::fill(st, &mut out);
        Ok(out)
    }

    fn complete_handshake(
        &self,
        st: &mut LinkState,
        msg: &[u8],
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let role = std::mem::replace(&mut st.role, Role::Closed);
        let peer_cert: core_device::DeviceCert;
        let mut applied = false;
        let up = match role {
            Role::Initiator(mut init) => {
                let (payload, h, keys) = init.read_message_2_bound(msg)?;
                let expected = st.peer.ok_or(FfiError::UnknownContact)?;
                let dh = self
                    .node
                    .lock()
                    .contacts
                    .get(&expected)
                    .map(|c| c.dh)
                    .ok_or(FfiError::UnknownContact)?;
                // (c) device binding: certificate for this session's key + signature over h.
                let cert = core_device::verify_handshake_payload(&payload, &h, &dh)?;
                let peer = self.node.lock().resolve_peer(expected, &cert)?;
                st.peer = Some(peer);
                peer_cert = cert;
                Established {
                    link: LinkSession::initiator(&keys),
                    keys,
                    initiator: true,
                    reasm: FragmentReassembler::default(),
                    app_send: 0,
                    app_recv: 0,
                }
            }
            Role::Responder(mut resp) => {
                let (payload, h) = resp.read_message_1_bound(msg)?;
                let rs = resp.remote_static().ok_or(FfiError::UnknownContact)?;
                // (c) device binding; then find the contact by PeerID (or a legacy
                // contact by its X25519 id). Unknown initiators are refused
                // (beta requires mutual QR add).
                let cert = core_device::verify_handshake_payload(&payload, &h, &rs)?;
                let peer = {
                    let mut node = self.node.lock();
                    let expected = if node.contacts.contains_key(&cert.peer_id) {
                        cert.peer_id
                    } else if node.contacts.get(&rs).is_some_and(|c| c.legacy(&rs)) {
                        rs
                    } else {
                        return Err(FfiError::UnknownContact);
                    };
                    let peer = node.resolve_peer(expected, &cert)?;
                    // RS1/RS2 before answering: a superseded device key fails here.
                    node.apply_peer_cert(peer, &cert, now_ms(), out)?;
                    peer
                };
                applied = true;
                let node = &self.node;
                let (m2, keys) = resp.write_message_2_with(|h| node.handshake_payload(h))?;
                chunk_handshake(&m2, &mut out.outgoing)?;
                peer_cert = cert;
                st.peer = Some(peer);
                Established {
                    link: LinkSession::responder(&keys),
                    keys,
                    initiator: false,
                    reasm: FragmentReassembler::default(),
                    app_send: 0,
                    app_recv: 0,
                }
            }
            other => {
                st.role = other;
                return Err(FfiError::State {
                    msg: "unexpected handshake message".into(),
                });
            }
        };
        if let (Some(p), false) = (st.peer, applied) {
            // RS1: the contact's device decides about the restore notice.
            self.node
                .lock()
                .apply_peer_cert(p, &peer_cert, now_ms(), out)?;
        }
        st.role = Role::Up(Box::new(up));
        if let Some(p) = st.peer {
            let mut node = self.node.lock();
            node.links_up.insert(self.handle, p);
            // CB3: ask the partner again for every missing-media placeholder.
            node.request_missing_media(&p, out)?;
        }
        self.flush_locked(st, out)
    }
}

